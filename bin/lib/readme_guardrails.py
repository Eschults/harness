"""Builds README.md's Guardrails list from the first sentence of each .claude/harness-rules.md section."""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent.parent
RULES_PATH = ".claude/harness-rules.md"
START_MARKER = "<!-- guardrails:start (generated by bin/sync-readme from .claude/harness-rules.md) -->"
END_MARKER = "<!-- guardrails:end -->"
SKIP_MARKER = "<!-- readme-guardrails: skip -->"
_NOT_PROSE = re.compile(r"^(?:[-*+]\s|\d+[.)]\s|#|<!--|```)")
_SENTENCE = re.compile(r"(.+?[.!?])(?=\s+[A-Z`*\[]|$)")


def strip_fenced_code_blocks(text: str) -> str:
    """Drop ```...``` blocks so example headings/links inside them aren't mistaken for real ones."""
    return re.sub(r"```.*?```", "", text, flags=re.DOTALL)


def heading_anchor(heading: str) -> str:
    """GitHub-style heading slug: lowercase, drop punctuation, spaces to hyphens."""
    return re.sub(r"\s+", "-", re.sub(r"[^\w\s-]", "", heading.lower()).strip())


def _summary_sentence(section_body: str) -> str | None:
    for paragraph in re.split(r"\n\s*\n", section_body.strip()):
        lines = [line for line in paragraph.splitlines() if not line.strip().startswith("<!--")]
        prose = " ".join(" ".join(lines).split())
        if not prose:
            continue
        if _NOT_PROSE.match(prose):
            return None
        match = _SENTENCE.match(prose)
        return match.group(1) if match else None
    return None


def guardrail_bullets(rules_text: str) -> list[str]:
    """One bullet per rules section; raises ValueError for a section with no summary sentence."""
    sections = re.split(r"(?m)^## +(.+?)\s*$", strip_fenced_code_blocks(rules_text))[1:]
    bullets = []
    for heading, body in zip(sections[0::2], sections[1::2]):
        if SKIP_MARKER in body:
            continue
        summary = _summary_sentence(body)
        if summary is None:
            raise ValueError(f"{RULES_PATH} section {heading!r} needs a one-sentence summary above its bullets")
        bullets.append(f"- **[{heading}]({RULES_PATH}#{heading_anchor(heading)})**: {summary}")
    return bullets


def synced_readme(readme_text: str, rules_text: str) -> str:
    before, start, rest = readme_text.partition(START_MARKER)
    _, end, after = rest.partition(END_MARKER)
    if not start or not end:
        raise ValueError(f"README.md is missing the {START_MARKER!r} / {END_MARKER!r} markers")
    generated = "\n".join(guardrail_bullets(rules_text))
    return f"{before}{START_MARKER}\n{generated}\n{END_MARKER}{after}"
